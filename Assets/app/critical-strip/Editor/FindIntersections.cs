    [MenuItem("Critical Strip/Test Known values for intersection")]
    public static void TestKnownIntersections()
    {
        // Known intersection values to test
        double[] knownValues = { 0.078987, 0.500029, 0.921013 };
        double scanRange = 0.001; // Scan ±0.001 around each known value
        double stepSize = 0.0000001; // Use even finer steps
        
        var results = new StringBuilder();
        results.AppendLine("=== Known Intersection Values Analysis ===");
        results.AppendLine($"Critical Index: {CRITICAL_INDEX:F15}");
        results.AppendLine("Scanning ±0.001 with step size 0.000001");
        results.AppendLine();
        
        foreach (double knownT in knownValues)
        {
            Debug.Log($"\nTesting around known intersection t={knownT:F15}");
            double minDistance = double.MaxValue;
            double bestT = knownT;
            
            // Scan around the known value
            for (double t = knownT - scanRange; t <= knownT + scanRange; t += stepSize)
            {
                Vector2 p1 = RhombusPoints.GetBPSymmetry((float)t, (float)CRITICAL_INDEX);
                Vector2 p2 = RhombusPoints.GetBPForward((float)t, (float)CRITICAL_INDEX);
                double distance = Vector2.Distance(p1, p2);
                
                if (distance < minDistance)
                {
                    minDistance = distance;
                    bestT = t;
                }
            }
            
            // Get the points at the best t value for detailed output
            Vector2 bestP1 = RhombusPoints.GetBPSymmetry((float)bestT, (float)CRITICAL_INDEX);
            Vector2 bestP2 = RhombusPoints.GetBPForward((float)bestT, (float)CRITICAL_INDEX);
            
            results.AppendLine($"Known t = {knownT:F15}");
            results.AppendLine($"Best t found = {bestT:F15}");
            results.AppendLine($"Minimum distance = {minDistance:E15}");
            results.AppendLine($"Symmetry point = ({bestP1.x:F6}, {bestP1.y:F6})");
            results.AppendLine($"Forward point = ({bestP2.x:F6}, {bestP2.y:F6})");
            results.AppendLine($"Difference from known = {System.Math.Abs(bestT - knownT):E15}");
            results.AppendLine();
        }
        
        Debug.LogWarning(results.ToString());
    }

    [MenuItem("Critical Strip/Test Precise Intersection Values")]
    public static void TestPreciseIntersectionValues()
    {
        // Known intersection values to test (using the updated known values from the renderer)
        double[] knownValues = { 0.079987, 0.500029, 0.920013 };
        
        // Coarse scan parameters
        double coarseScanRange = 0.001;    // ±0.001 around the known value
        double coarseStep = 0.0000001;     // Coarse step size: 1e-7
        
        // Fine scan parameters
        double fineScanRange = 0.00001;      // ±0.00001 around the coarse best value
        double fineStep = 0.00000001;        // Fine step size: 1e-8
        
        var consolidatedLog = new StringBuilder();
        consolidatedLog.AppendLine("=== Precise Intersection Values Analysis ===");
        consolidatedLog.AppendLine($"Critical Index: {CRITICAL_INDEX:F15}");
        consolidatedLog.AppendLine();
        
        foreach (double knownT in knownValues)
        {
            consolidatedLog.AppendLine($"--- Analysis for Known t = {knownT:F15} ---");
            
            // Coarse scan: find preliminary best t
            double bestT_coarse = knownT;
            double minDist_coarse = double.MaxValue;
            for (double t = knownT - coarseScanRange; t <= knownT + coarseScanRange; t += coarseStep)
            {
                Vector2 sp = RhombusPoints.GetBPSymmetry((float)t, (float)CRITICAL_INDEX);
                Vector2 fp = RhombusPoints.GetBPForward((float)t, (float)CRITICAL_INDEX);
                double dist = Vector2.Distance(sp, fp);
                if (dist < minDist_coarse)
                {
                    minDist_coarse = dist;
                    bestT_coarse = t;
                }
            }
            consolidatedLog.AppendLine($"Coarse Scan: Best t = {bestT_coarse:F15}, distance = {minDist_coarse:E15}");
            consolidatedLog.AppendLine();
            
            // Fine scan: more densely sample around bestT_coarse
            double bestT_fine = bestT_coarse;
            double minDist_fine = double.MaxValue;
            var fineScanLog = new StringBuilder();
            fineScanLog.AppendLine("t, distance, symmetry_x, symmetry_y, forward_x, forward_y");
            for (double t = bestT_coarse - fineScanRange; t <= bestT_coarse + fineScanRange; t += fineStep)
            {
                Vector2 sp = RhombusPoints.GetBPSymmetry((float)t, (float)CRITICAL_INDEX);
                Vector2 fp = RhombusPoints.GetBPForward((float)t, (float)CRITICAL_INDEX);
                double dist = Vector2.Distance(sp, fp);
                if (dist < minDist_fine)
                {
                    minDist_fine = dist;
                    bestT_fine = t;
                }
                fineScanLog.AppendLine($"{t:F15}, {dist:E15}, {sp.x:F6}, {sp.y:F6}, {fp.x:F6}, {fp.y:F6}");
            }
            consolidatedLog.AppendLine($"Fine Scan: Best t = {bestT_fine:F15}, distance = {minDist_fine:E15}");
            consolidatedLog.AppendLine("Detailed Dense Sampling Data:");
            consolidatedLog.Append(fineScanLog.ToString());
            consolidatedLog.AppendLine();
        }
        Debug.LogWarning(consolidatedLog.ToString());
    }

