    [MenuItem("Critical Strip/Find Equal Leg Lengths Around Critical Index")]
    public static void FindEqualLegLengthsAroundCriticalIndex()
    {
        var equalLegsData = new List<(double real, double index, Vector2 point)>();

        // Check the range with regular steps
        int totalSteps = (int)System.Math.Ceiling((MAX_INDEX - MIN_INDEX) / INDEX_STEP);
        int currentStep = 0;
        
        bool IsFractionalPartInRange(double value, double min, double max)
        {
            double frac = value - Math.Floor(value);
            return frac >= min && frac <= max;
        }

        for (double index = MIN_INDEX; index <= MAX_INDEX; index += INDEX_STEP)
        {
            if (EditorUtility.DisplayCancelableProgressBar(
                "Finding Equal Leg Lengths",
                $"Processing index {index:F15}",
                (float)currentStep / totalSteps))
            {
                EditorUtility.ClearProgressBar();
                Debug.Log("Equal leg lengths finding cancelled.");
                return;
            }
            
            bool OneForth = IsFractionalPartInRange(index, 0.25, 0.26);
            if(index < 3.0) OneForth = IsFractionalPartInRange(index, 0.25, 0.27);

            bool ThreeForths = IsFractionalPartInRange(index, 0.75, 0.76);

            // if currentTheta is less than the previous theta, we are close to counterflux / window point
            if (OneForth || ThreeForths)
            {
                FindEqualLegLengths(index, equalLegsData);
            }

            currentStep++;
        }

        EditorUtility.ClearProgressBar();
        SaveToCSV(equalLegsData);
    }

    private static void FindEqualLegLengths(double index, List<(double real, double index, Vector2 point)> equalLegsData)
    {
        const int realResolution = 100 + 1; // even numbers run into issues at real = 1/2
        double dt = 1.0 / realResolution;
        double[] distances = new double[realResolution];
        double[] ts = new double[realResolution];

        for (int i = 0; i < realResolution; i++)
        {
            double t = i * dt;
            ts[i] = t;
            distances[i] = ZpsGeneral.ForwardBisector(t, index).Length - ZpsGeneral.InverseBisector(t, index).Length;
        }

        List<int> crossings = new List<int>();
        // find when the distance changes sign
        for (int i = 0; i < realResolution - 1; i++)
        {
            double d0 = distances[i];
            double d1 = distances[i + 1];
            // Check if the distance is crossing zero
            if ((d0 > 0 && d1 < 0) || (d0 < 0 && d1 > 0))
            {
                crossings.Add(i);
            }
        }
        
        // sanity check
        if (crossings.Count != 1 && crossings.Count != 3)
        {
            Debug.LogWarning($"Unexpected number of crossings: {crossings.Count} at index {index:F15}");
        }

        if (crossings.Count == 1)
        {
            return; //skip only 0.5 crossing
        }
        
        for (int i = 0; i < crossings.Count - 1; i++)
        {
            if (i == 1 && crossings.Count == 3)
            {
                i += 1; // skip 0.5 crossing
            }
            
            int crossingIndex = crossings[i];
            double real = ts[crossingIndex];
            double realNext = ts[crossingIndex + 1];

            if (Vector3.Dot(ZpsGeneral.ForwardBisector(real, index).Normalized(), ZpsGeneral.ForwardBisector(realNext, index).Normalized()) < 0)
            {
                continue; // we flipped the intersection side, skip this point
            }

            // We have a crossing, find the exact point
            double low = real;
            double high = realNext;
            for (int iter = 0; iter < 20; iter++)
            {
                double mid = (low + high) / 2.0;
                double midDist = ZpsGeneral.ForwardBisector(mid, index).Length - ZpsGeneral.InverseBisector(mid, index).Length;
                if (Math.Abs(midDist) < 1e-6) { low = mid; high = mid; break; } // found zero distance

                // Use the sign of the distance at the endpoints to determine which side to keep
                double lowDist = ZpsGeneral.ForwardBisector(low, index).Length - ZpsGeneral.InverseBisector(low, index).Length;
                if (Math.Sign(midDist) == Math.Sign(lowDist))
                    low = mid;
                else
                    high = mid;
            }

            double refinedT = (low + high) / 2.0;

            equalLegsData.Add((refinedT, index, new Vector(refinedT, index)));
        }

    }

    private static void FindThetaData(double index, List<(double real, double index, Vector2 point)> thetaData)
    {
        var twoPI = 2.0 * Math.PI;
        var ThetaTwo = -BisectorPoint.ThetaTwo(index);
        var phase = (ThetaTwo % twoPI) / twoPI;
        var pt = new Vector(phase, index);
        thetaData.Add((phase, index, pt));
    }

    private static void FindIntersectionsForIndex(double index, List<(double real, double index, Vector2 point)> intersectionData)
    {
        var path1 = new Vector2[POINTS_PER_PATH];
        var path2 = new Vector2[POINTS_PER_PATH];
        
        // Generate paths with higher resolution
        for (int i = 0; i < POINTS_PER_PATH; i++)
        {
            double r = (double)i / POINTS_PER_PATH;
            path1[i] = RhombusPoints.GetBPSymmetry((float)r, (float)index);
            path2[i] = RhombusPoints.GetBPForward((float)r, (float)index);
        }
        
        var intersections = FindPathIntersections(path1, path2);
        Debug.Log($"Found {intersections.Length} intersections for index {index:F15}");
        
        foreach (var intersection in intersections)
        {
            // Find closest point in either path to get real value
            double closestDist = double.MaxValue;
            double closestReal = 0.0;
            
            for (int i = 0; i < path1.Length; i++)
            {
                double dist = Vector2.Distance(path1[i], intersection);
                if (dist < closestDist)
                {
                    closestDist = dist;
                    closestReal = (double)i / POINTS_PER_PATH;
                }
            }
            
            for (int i = 0; i < path2.Length; i++)
            {
                double dist = Vector2.Distance(path2[i], intersection);
                if (dist < closestDist)
                {
                    closestDist = dist;
                    closestReal = (double)i / POINTS_PER_PATH;
                }
            }
            
            intersectionData.Add((closestReal, index, intersection));
        }
    }

    private static Vector2[] FindPathIntersections(Vector2[] path1, Vector2[] path2)
    {
        var intersections = new List<Vector2>();
        
        // Check each line segment pair for intersections
        for (int i = 1; i < path1.Length; i++)
        {
            var line1Start = path1[i - 1];
            var line1End = path1[i];
            
            for (int j = 1; j < path2.Length; j++)
            {
                var line2Start = path2[j - 1];
                var line2End = path2[j];
                
                if (TryGetLineIntersection(line1Start, line1End, line2Start, line2End, out Vector2 intersection))
                {
                    intersections.Add(intersection);
                }
            }
        }
        
        return intersections.ToArray();
    }

    private static bool TryGetLineIntersection(Vector2 line1Start, Vector2 line1End, Vector2 line2Start, Vector2 line2End, out Vector2 intersection)
    {
        intersection = Vector2.zero;

        double a1 = line1End.y - line1Start.y;
        double b1 = line1Start.x - line1End.x;
        double c1 = a1 * line1Start.x + b1 * line1Start.y;

        double a2 = line2End.y - line2Start.y;
        double b2 = line2Start.x - line2End.x;
        double c2 = a2 * line2Start.x + b2 * line2Start.y;

        double determinant = a1 * b2 - a2 * b1;

        if (System.Math.Abs(determinant) < 1e-10)
            return false;

        double x = (b2 * c1 - b1 * c2) / determinant;
        double y = (a1 * c2 - a2 * c1) / determinant;
        intersection = new Vector2((float)x, (float)y);

        return IsPointOnLineSegment(line1Start, line1End, intersection) &&
               IsPointOnLineSegment(line2Start, line2End, intersection);
    }

    private static bool IsPointOnLineSegment(Vector2 lineStart, Vector2 lineEnd, Vector2 point)
    {
        double d1 = Vector2.Distance(lineStart, point);
        double d2 = Vector2.Distance(lineEnd, point);
        double lineLength = Vector2.Distance(lineStart, lineEnd);
        double buffer = 1e-10;

        return d1 + d2 >= lineLength - buffer && d1 + d2 <= lineLength + buffer;
    }

