/*
*** DO NOT DELETE ***
This file contains editor utilities for analyzing intersections in the Critical Strip.
It includes functions which perform dense sampling of the two paths generated by
RhombusPoints.GetBPSymmetry and RhombusPoints.GetBPForward for a given critical index.

Available Functions:
- TestKnownIntersections: Scans ±0.001 around known t values with fine steps and logs the minimal distance and corresponding points.
- TestPreciseIntersectionValues: Performs a coarse scan followed by a fine scan to densely sample the distance function around each candidate intersection.
- TestExactIntersection: For each known intersection candidate, it zeroes in on the best t value, then uses two points from each path (taken at a small epsilon around the best t)
  to form two line segments. A simple line intersection algorithm is used to compute the exact intersection point of these lines,
  approximating the true intersection as closely as double precision allows.

The goal is to investigate and determine the true intersection values despite small numerical offsets.
*** END OF DO NOT DELETE HEADER ***
*/

