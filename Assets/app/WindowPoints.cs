        {
            int pt = (int)value;
            LoadWindowPoint(pt);
            _windowPointInputText.SetText(pt.ToString());
        });

        _windowPointInputSlider.minValue = 0;
        _windowPointInputSlider.maxValue = _windowList.Count-1;
    }

    public void LoadWindowPoint(int index)
    {
